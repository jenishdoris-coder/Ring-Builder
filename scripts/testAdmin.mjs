import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { createHmac, scryptSync } from "node:crypto";
import ts from "typescript";
const moduleUrl = async path => {
  const source = await readFile(new URL(path, import.meta.url), "utf8");
  let output = ts.transpileModule(source, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext } }).outputText;
  if (path.endsWith("/catalog.ts")) output = output.replace('"../utils/ringPricing"', JSON.stringify(await moduleUrl("../src/utils/ringPricing.ts")));
  if (path.endsWith("/deletion.ts")) output = output.replace('"./catalog"',JSON.stringify(await moduleUrl("../src/admin/catalog.ts"))).replace('"../utils/ringPricing"',JSON.stringify(await moduleUrl("../src/utils/ringPricing.ts")));
  return `data:text/javascript;base64,${Buffer.from(output).toString("base64")}`;
};
const moduleAt = async path => import(await moduleUrl(path));
const { validateCatalog, storefrontCatalog, publicCatalog } = await moduleAt("../src/admin/catalog.ts");
const source = JSON.parse(await readFile(new URL("../src/config/catalog.json", import.meta.url), "utf8"));
const prefix = "https://assets.example.com/ring-builder/releases/test/";
const catalog = { ...source, schemaVersion: 1, releaseId: "test", assetBaseUrl: prefix.slice(0,-1), shapes: source.shapes.map(shape => ({ ...shape, carats: shape.carats.map(head => ({ ...head, file: prefix + head.file.slice(1) })) })), shanks: source.shanks.map(band => ({ ...band, file: prefix + band.file.slice(1) })) };
assert.deepEqual(validateCatalog(catalog, [prefix]), []);
const invalid = change => { const next = structuredClone(catalog); change(next); assert.ok(validateCatalog(next, [prefix]).length); };
invalid(next => { next.shanks[0].file = "https://untrusted.example/model.glb"; });
invalid(next => { next.shanks[0].file = "javascript:alert(1)"; });
invalid(next => { next.shanks.push(next.shanks[0]); });
invalid(next => { next.shanks.find(item => item.id === next.defaults.shankId).enabled = false; });
invalid(next => { next.shapes.find(item => item.id === next.defaults.shapeId).enabled = false; });
invalid(next => { next.metals[0].hexCode = "red; background:url(x)"; });
invalid(next => { next.defaults.headScale = 0; });
invalid(next => { next.shapes[0].carats.push(next.shapes[0].carats[0]); });
invalid(next => { next.shapes[0].carats = [null]; });
invalid(next => { next.shanks[0].thumbnail = `${prefix}image.svg`; });
const hidden = structuredClone(catalog);
hidden.shanks.find(item => item.id !== hidden.defaults.shankId).enabled = false;
hidden.shapes.find(item => item.id !== hidden.defaults.shapeId).carats[0].enabled = false;
assert.equal(storefrontCatalog(hidden).shanks.length, catalog.shanks.length - 1);
assert.deepEqual(validateCatalog(hidden, [prefix]), []);
const { emptyPricing, quoteRing, headPriceKey, bandPriceKey, componentPricingOnly } = await moduleAt("../src/utils/ringPricing.ts");
const p = emptyPricing();
assert.equal(p.currency,"USD");
p.enabled=true; p.multiplier=1.5; p.diamondPerCarat=1000; p.accentDiamondPerCarat=200;
p.metalRates.white_gold={perGram:100,finishCharge:10}; p.metalRates.yellow_gold={perGram:120,finishCharge:20};
p.heads[headPriceKey("4-prong-talon",2)]={mode:"weights",goldGrams:1,diamondCarats:.1};
p.bands[bandPriceKey("traditional-solitaire","7")]={mode:"weights",goldGrams:3,diamondCarats:.2};
p.bands[bandPriceKey("traditional-solitaire","8")]={mode:"weights",goldGrams:4,diamondCarats:.2};
const selection={shapeId:"round",carat:2,headStyleId:"4-prong-talon",bandId:"traditional-solitaire",headMetalId:"white_gold",bandMetalId:"yellow_gold",size:"7"};
let quote=quoteRing(catalog,selection,p);
assert.equal(quote.total,3825,"sum center, separate head/band metals, accent diamonds and finishes before applying multiplier once");
assert.equal(quote.goldGrams,4);
assert.ok(Math.abs(quote.diamondCarats-2.3)<1e-9);
assert.equal(quoteRing(catalog,{...selection,size:"8"},p).total,4005,"band size changes measured weights only");
p.centerRates["round|2"]=1500;
assert.equal(quoteRing(catalog,selection,p).total,5325,"center rate overrides multiply the actual center diamond carat");
delete p.centerRates["round|2"];
p.heads[headPriceKey("4-prong-talon",2,"round")]={mode:"weights",goldGrams:1.5,diamondCarats:.1};
assert.equal(quoteRing(catalog,selection,p).total,3900,"shape-specific head weights override style defaults");
delete p.heads[headPriceKey("4-prong-talon",2,"round")];
p.heads[headPriceKey("4-prong-talon",2)]={mode:"fixed",fixedPrice:150,metalPrices:{white_gold:175}};
assert.equal(quoteRing(catalog,selection,p).total,3892.5,"a fixed component is not charged its material or finish costs again");
p.mode="fixed"; p.fixedPrice=1; p.fixedVariants={};
assert.equal(quoteRing(catalog,selection,p).total,3892.5,"legacy whole-ring prices cannot override selected components");
assert.equal(componentPricingOnly(p).fixedPrice,undefined);
assert.equal(componentPricingOnly(p).mode,undefined);
assert.equal(quoteRing(catalog,{...selection,size:"unknown"},p).total,null);
delete p.metalRates.yellow_gold;
assert.equal(quoteRing(catalog,selection,p).total,null,"missing prices are never silently replaced with zero");
catalog.pricing=p;
const publicData=publicCatalog(catalog);
assert.equal(publicData.pricing,undefined,"costs and the multiplier never enter the public catalog");
assert.equal(publicData.pricingPublic.currency,"USD");
assert.equal(JSON.stringify(publicData).includes('"goldGrams"'),false);
const otherStyle=structuredClone(catalog);
otherStyle.headStyles=[{id:"4-prong-talon",name:"4-Prong Talon"},{id:"hidden-halo",name:"Hidden Halo"}];
otherStyle.shapes[0].carats.push({...otherStyle.shapes[0].carats[0],styleId:"hidden-halo"});
assert.deepEqual(validateCatalog(otherStyle,[prefix]),[],"a second setting can reuse a shape and carat without clashing");

const {deleteCatalogItem}=await moduleAt("../src/admin/deletion.ts");
const deletable=structuredClone(catalog);
deletable.pricing.heads[headPriceKey("4-prong-talon",2,"round")]={mode:"weights",goldGrams:1,diamondCarats:0};
deletable.pricing.centerRates["round|2"]=1500;
const snapshot=JSON.stringify(deletable);
const removedBand=deleteCatalogItem(deletable,{kind:"band",id:deletable.defaults.shankId});
assert.equal(removedBand.catalog.shanks.length,deletable.shanks.length-1);
assert.notEqual(removedBand.catalog.defaults.shankId,deletable.defaults.shankId);
assert.equal(Object.keys(removedBand.catalog.pricing.bands).some(key=>key.startsWith(deletable.defaults.shankId+"|")),false);
assert.deepEqual(validateCatalog(removedBand.catalog,[prefix]),[]);
const removedHead=deleteCatalogItem(deletable,{kind:"head",shapeId:"round",styleId:"4-prong-talon",carat:2});
assert.equal(removedHead.catalog.defaults.carat,1.5,"deleting the default head selects the nearest available carat");
assert.ok(removedHead.catalog.pricing.heads[headPriceKey("4-prong-talon",2)],"shared setting weights stay for other shapes");
assert.equal(removedHead.catalog.pricing.heads[headPriceKey("4-prong-talon",2,"round")],undefined);
assert.equal(removedHead.catalog.pricing.centerRates["round|2"],undefined);
const removedMetal=deleteCatalogItem(deletable,{kind:"metal",id:"white_gold"});
assert.equal(removedMetal.catalog.metals.some(item=>item.id==="white_gold"),false);
assert.equal(removedMetal.catalog.pricing.metalRates.white_gold,undefined);
assert.equal(removedMetal.catalog.pricing.heads[headPriceKey("4-prong-talon",2)].metalPrices.white_gold,undefined);
assert.deepEqual(validateCatalog(removedMetal.catalog,[prefix]),[]);
const removedShape=deleteCatalogItem(deletable,{kind:"shape",id:"round"});
assert.notEqual(removedShape.catalog.defaults.shapeId,"round");
assert.deepEqual(validateCatalog(removedShape.catalog,[prefix]),[]);
const removedStyle=deleteCatalogItem(otherStyle,{kind:"style",id:"4-prong-talon"});
assert.equal(removedStyle.catalog.defaults.headStyleId,"hidden-halo");
assert.equal(removedStyle.catalog.shapes.reduce((total,shape)=>total+shape.carats.length,0),1);
assert.deepEqual(validateCatalog(removedStyle.catalog,[prefix]),[]);
assert.throws(()=>deleteCatalogItem({...deletable,shanks:deletable.shanks.filter(item=>item.id===deletable.defaults.shankId)},{kind:"band",id:deletable.defaults.shankId}),/at least one/);
assert.throws(()=>deleteCatalogItem({...deletable,metals:[deletable.metals[0]]},{kind:"metal",id:deletable.metals[0].id}),/at least one/);
assert.throws(()=>deleteCatalogItem(deletable,{kind:"style",id:"4-prong-talon"}),/at least one/);
assert.equal(JSON.stringify(deletable),snapshot,"deletion previews never mutate the current draft or its files");

